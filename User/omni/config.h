#ifndef OMNI_CONFIG_H
#define OMNI_CONFIG_H

/*
 * 底盘集中参数表
 *
 * 这里保存需要实测、整定或长期调整的参数。修改后重新编译下载。
 * CAN报文格式、ET07帧格式和电机协议量程属于固定协议，继续留在各自驱动中。
 */

/* ==================== 电机与轮序 ==================== */

/* C620拨码ID。四轮在控制器中的固定顺序为左前、左后、右后、右前。 

        车头
   m1           m4     
    \          /
     \        /
        底盘
     /        \
    /          \
   m2           m3 */
#define MOTOR_ID_FL       (1U)    /* 左前轮 */
#define MOTOR_ID_RL       (2U)    /* 左后轮 */
#define MOTOR_ID_RR       (3U)    /* 右后轮 */
#define MOTOR_ID_FR       (4U)    /* 右前轮 */

/* 目标方向不一致时，将对应值改为-1.0f。 */
#define MOTOR_DIR_FL      (1.0f)
#define MOTOR_DIR_FR      (1.0f)
#define MOTOR_DIR_RL      (1.0f)
#define MOTOR_DIR_RR      (1.0f)

/* 电机反馈超时，单位ms；任一轮超时后四轮同时停止。 */
#define MOTOR_TIMEOUT_MS  (50U)

/* ==================== 机械参数 ==================== */

/* M3508减速箱传动比：电机转子转速 / 车轮转速。 */
#define GEAR_RATIO        (3591.0f / 187.0f)

/* 车轮有效半径，单位m；后续用实际行驶距离校准。 */
#define WHEEL_R           (0.076f)

/* 旋转等效半径，单位m；后续用原地旋转角速度校准。 */
#define ROT_R             (0.180f)

/* ==================== 控制周期与输出限制 ==================== */

/* 底盘控制周期，单位ms；CTRL_DT是PID使用的秒制周期。 */
#define CTRL_MS           (2U)
#define CTRL_DT           ((float)CTRL_MS * 0.001f)

/* 电机转子目标转速上限，单位rpm；超限时四轮统一缩放。 */
#define RPM_MAX           (9256.0f)//空载上限9256，经过减速器后为 9256/19.2=482.29rpm，经过轮子后轮缘线速度为482.29*2*3.14*wheel_R/60=3.83m/s
//所需RPM_MAX ≥ 2412.86 × [(|vx| + |vy|)/√2 + 0.160×|wz|]
//K（当为1m/s时的电机转子转速）=2412.86RPM
//0.160为旋转等效半径ROT_R，wz为小陀螺角速度

//1m/s对应电机转子转速为K：K= （1m/2*3.14*WHEEL_R）*60*G=2412.86RPM
//故1m/s对应的电机转子转速为2412.86RPM，电机目标速度*K=电机目标转子转速
//电机目标速度=经过底盘解算后的底盘目标速度（注意不同方向叠加）
//在小陀螺状态下，


/* C620电流命令上限。1000 raw约等于1.22 A。 */
#define CURRENT_MAX       (16384)//16384对应20A上限

/* ==================== 轮速PID ==================== */

/* 四个轮速环共用一组参数，输出单位为C620电流命令raw。 */
#define PID_KP            (6.0f)
#define PID_KI            (0.1f)
#define PID_KD            (0.0f)

/* 积分状态的绝对上限。 */
#define PID_I_MAX         (1.0f)

/* 微分低通系数。1.0表示不滤波；当前Kd为0，该值暂不影响输出。 */
#define PID_D_ALPHA       (0.2f)

/* ==================== ET07遥控标定 ==================== */

/* CH3、CH4和SC使用的原始11位通道端点与中位。 */
#define RC_MIN            (240U)
#define RC_CENTER         (1024U)
#define RC_MAX            (1807U)

/* 摇杆中位死区，单位raw，应略大于实测中位抖动。 */
#define RC_DEADBAND       (5U)

/* 遥控有效帧超时，单位ms。 */
#define RC_TIMEOUT_MS     (100U)

/* 解锁时允许的摇杆中位范围，占归一化行程的比例。 */
#define ARM_NEUTRAL       (0.05f)

/* 底盘速度限制。 */
#define MAX_VX            (5.430f)   /* 前后最大速度，m/s */ //放开轮速以及电流限制，理论纯前后移动速度最大为5.43m/s
#define MAX_VY            (5.430f)   /* 左右最大速度，m/s */ //放开轮速以及电流限制，理论纯左右移动速度最大为5.43m/s，
#define SPIN_WZ           (12.56f)   /* 小陀螺角速度，rad/s */ //放开轮速以及电流限制，理论纯小陀螺旋转速度最大为21.31rad/s，
//即约21.31rad/s = 21.31 * 57.296°/s ≈ 1220°/s

/*前后左右合起来也是5.43m/s，
  原因是前后左右速度叠加时，轮子转速不变，电机转速不变，电机电流不变，电机功率不变，所以理论上最大速度还是5.43m/s*/
/* ==================== 安全门 ==================== */

/* 遥控健康、SC上档且摇杆回中需要连续保持的时间，单位ms。 */
#define ARM_TIME_MS       (200U)

#endif
